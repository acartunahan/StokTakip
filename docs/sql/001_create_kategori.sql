CREATE TABLE KATEGORI (
    GUID VARCHAR2(36) NOT NULL,
    PARENT VARCHAR2(36),
    BASLIK VARCHAR2(100) NOT NULL,
    TUR VARCHAR2(20) NOT NULL,
    TARIH TIMESTAMP,
    CONSTRAINT PK_KATEGORI PRIMARY KEY (GUID),
    CONSTRAINT FK_KATEGORI_PARENT FOREIGN KEY (PARENT)
        REFERENCES KATEGORI (GUID)
);

CREATE INDEX IX_KATEGORI_PARENT ON KATEGORI (PARENT);
CREATE INDEX IX_KATEGORI_TUR ON KATEGORI (TUR);
