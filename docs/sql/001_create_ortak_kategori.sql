CREATE TABLE ORTAK_KATEGORI (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    GUID VARCHAR2(36) NOT NULL,
    UST_KATEGORI_GUID VARCHAR2(36),
    KATEGORI_TURU VARCHAR2(20) NOT NULL,
    ADI VARCHAR2(100) NOT NULL,
    ACIKLAMA VARCHAR2(200),
    R_DEPOGUID VARCHAR2(36),
    DURUM CHAR(1),
    K_TARIH DATE,
    CONSTRAINT PK_ORTAK_KATEGORI PRIMARY KEY (GUID),
    CONSTRAINT UK_ORTAK_KATEGORI_ID UNIQUE (ID),
    CONSTRAINT CK_ORTAK_KATEGORI_TUR CHECK (KATEGORI_TURU IN ('SARF', 'SABIT_KOD')),
    CONSTRAINT FK_ORTAK_KATEGORI_UST FOREIGN KEY (UST_KATEGORI_GUID)
        REFERENCES ORTAK_KATEGORI (GUID)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX IX_ORTAK_KATEGORI_UST ON ORTAK_KATEGORI (UST_KATEGORI_GUID);
CREATE INDEX IX_ORTAK_KATEGORI_TUR ON ORTAK_KATEGORI (KATEGORI_TURU);
