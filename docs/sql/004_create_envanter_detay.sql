CREATE TABLE ENVANTER_DETAY (
    GUID VARCHAR2(128) NOT NULL,
    OLUSTURMA_TARIHI TIMESTAMP,
    GUNCELLEME_TARIHI TIMESTAMP,
    AKTIF NUMBER(1),
    ALIM_YOLU NUMBER,
    ALIM_TURU VARCHAR2(20),
    SAYMANLIK_NO VARCHAR2(100),
    IHALEGUID VARCHAR2(128),
    FIRMAGUID VARCHAR2(128),
    GARANTI_BASLANGIC_TARIHI TIMESTAMP,
    GARANTI_BITIS_TARIHI TIMESTAMP,
    CONSTRAINT PK_ENVANTER_DETAY PRIMARY KEY (GUID),
    CONSTRAINT FK_ENVANTER_DETAY_ENVANTER FOREIGN KEY (GUID)
        REFERENCES ENVANTER (GUID),
    CONSTRAINT FK_ENVANTER_DETAY_IHALE FOREIGN KEY (IHALEGUID)
        REFERENCES IHALE (GUID),
    CONSTRAINT FK_ENVANTER_DETAY_FIRMA FOREIGN KEY (FIRMAGUID)
        REFERENCES FIRMA (GUID)
);

CREATE INDEX IX_ENVANTER_DETAY_IHALE ON ENVANTER_DETAY (IHALEGUID);
CREATE INDEX IX_ENVANTER_DETAY_FIRMA ON ENVANTER_DETAY (FIRMAGUID);
