-- Existing target-schema migration: split ENVANTER_DETAY identity from ENVANTER.GUID.
-- Fresh installs do not need this file because 004_create_envanter_detay.sql already creates ENVANTER_GUID.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_ENVANTER_DETAY_ENVANTER';

    IF v_count > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE ENVANTER_DETAY DROP CONSTRAINT FK_ENVANTER_DETAY_ENVANTER';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'ENVANTER_DETAY'
      AND COLUMN_NAME = 'ENVANTER_GUID';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE ENVANTER_DETAY ADD (ENVANTER_GUID VARCHAR2(128))';
    END IF;
END;
/

UPDATE ENVANTER_DETAY
SET ENVANTER_GUID = GUID
WHERE ENVANTER_GUID IS NULL;

UPDATE ENVANTER_DETAY
SET GUID = LOWER(RAWTOHEX(STANDARD_HASH('ENVANTER_DETAY:' || ENVANTER_GUID, 'SHA256')))
WHERE ENVANTER_GUID IS NOT NULL
  AND GUID = ENVANTER_GUID;

ALTER TABLE ENVANTER_DETAY MODIFY ENVANTER_GUID VARCHAR2(128) NOT NULL;

