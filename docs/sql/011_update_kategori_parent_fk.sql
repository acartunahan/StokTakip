-- Existing target-schema migration: normalize KATEGORI.PARENT self foreign key.
-- Fresh installs do not need this file because 001_create_kategori.sql already creates this FK.

ALTER TABLE KATEGORI MODIFY (PARENT NULL);

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_KATEGORI_PARENT';

    IF v_count > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE KATEGORI DROP CONSTRAINT FK_KATEGORI_PARENT';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_CONSTRAINTS
    WHERE CONSTRAINT_NAME = 'FK_KATEGORI_PARENT_GUID';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE KATEGORI ADD CONSTRAINT FK_KATEGORI_PARENT_GUID FOREIGN KEY (PARENT) REFERENCES KATEGORI (GUID)';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IX_KATEGORI_PARENT';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_KATEGORI_PARENT ON KATEGORI (PARENT)';
    END IF;
END;
/

COMMIT;
