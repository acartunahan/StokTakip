-- Yeni uygulamanin Envanter tabanli zimmet yetenegi icindir.
-- Legacy kaynak ve migration audit tablolarina dokunmaz.

ALTER TABLE PERSONEL_ZIMMET_HAREKET ADD (PERSONEL_KODU VARCHAR2(100));
ALTER TABLE PERSONEL_ZIMMET_HAREKET ADD (HAREKET_TIPI VARCHAR2(32));
ALTER TABLE PERSONEL_ZIMMET_HAREKET ADD (APARAT_GUID VARCHAR2(128));
ALTER TABLE DEPO_ZIMMET_HAREKET ADD (HAREKET_TIPI VARCHAR2(32));
ALTER TABLE DEPO_ZIMMET_HAREKET ADD (APARAT_GUID VARCHAR2(128));

ALTER TABLE PERSONEL_ZIMMET_HAREKET ADD CONSTRAINT FK_PERSONEL_ZIMMET_APARAT
    FOREIGN KEY (APARAT_GUID) REFERENCES APARAT (GUID);
ALTER TABLE DEPO_ZIMMET_HAREKET ADD CONSTRAINT FK_DEPO_ZIMMET_APARAT
    FOREIGN KEY (APARAT_GUID) REFERENCES APARAT (GUID);

ALTER TABLE PERSONEL_ZIMMET_HAREKET ADD CONSTRAINT CK_PERSONEL_ZIMMET_TEK_VARLIK
    CHECK ((ENVANTER_GUID IS NOT NULL AND APARAT_GUID IS NULL)
        OR (ENVANTER_GUID IS NULL AND APARAT_GUID IS NOT NULL));
ALTER TABLE DEPO_ZIMMET_HAREKET ADD CONSTRAINT CK_DEPO_ZIMMET_TEK_VARLIK
    CHECK ((ENVANTER_GUID IS NOT NULL AND APARAT_GUID IS NULL)
        OR (ENVANTER_GUID IS NULL AND APARAT_GUID IS NOT NULL));

CREATE INDEX IX_PERSONEL_ZIMMET_ENV_AKTIF
    ON PERSONEL_ZIMMET_HAREKET (ENVANTER_GUID, AKTIF);
CREATE INDEX IX_PERSONEL_ZIMMET_APA_AKTIF
    ON PERSONEL_ZIMMET_HAREKET (APARAT_GUID, AKTIF);
CREATE INDEX IX_DEPO_ZIMMET_APARAT
    ON DEPO_ZIMMET_HAREKET (APARAT_GUID);

-- Legacy hareket ID'leriyle cakismamasi icin yeni uygulama ID alani yuksekten baslar.
CREATE SEQUENCE PERSONEL_ZIMMET_HAREKET_SEQ
    START WITH 1000000000000 INCREMENT BY 1 CACHE 100 NOCYCLE;
CREATE SEQUENCE DEPO_ZIMMET_HAREKET_SEQ
    START WITH 1000000000000 INCREMENT BY 1 CACHE 100 NOCYCLE;
