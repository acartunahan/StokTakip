DELETE FROM VERI_GOC_ID_ESLEME
WHERE UPPER(ESKI_TABLO_ADI) = 'R_APARAT'
   OR UPPER(HEDEF_VARLIK_ADI) = 'APARAT';

DELETE FROM VERI_GOC_ESKI_VERI_YUKU
WHERE UPPER(ESKI_TABLO_ADI) = 'R_APARAT'
   OR UPPER(HEDEF_VARLIK_ADI) = 'APARAT';

DELETE FROM VERI_GOC_HATA_KAYDI
WHERE UPPER(ESKI_TABLO_ADI) = 'R_APARAT';

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'PERSONEL_ZIMMET_HAREKET' AND COLUMN_NAME = 'APARAT_GUID';
    IF V_COUNT > 0 THEN
        EXECUTE IMMEDIATE 'DELETE FROM PERSONEL_ZIMMET_HAREKET WHERE APARAT_GUID IS NOT NULL';
        EXECUTE IMMEDIATE 'ALTER TABLE PERSONEL_ZIMMET_HAREKET DROP COLUMN APARAT_GUID CASCADE CONSTRAINTS';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'DEPO_ZIMMET_HAREKET' AND COLUMN_NAME = 'APARAT_GUID';
    IF V_COUNT > 0 THEN
        EXECUTE IMMEDIATE 'DELETE FROM DEPO_ZIMMET_HAREKET WHERE APARAT_GUID IS NOT NULL';
        EXECUTE IMMEDIATE 'ALTER TABLE DEPO_ZIMMET_HAREKET DROP COLUMN APARAT_GUID CASCADE CONSTRAINTS';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
    FROM USER_TABLES
    WHERE TABLE_NAME = 'APARAT';
    IF V_COUNT > 0 THEN
        EXECUTE IMMEDIATE 'DROP TABLE APARAT CASCADE CONSTRAINTS PURGE';
    END IF;
END;
/

ALTER TABLE PERSONEL_ZIMMET_HAREKET MODIFY (ENVANTER_GUID NOT NULL);
ALTER TABLE DEPO_ZIMMET_HAREKET MODIFY (ENVANTER_GUID NOT NULL);

COMMIT;
